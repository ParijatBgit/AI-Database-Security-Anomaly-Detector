SELECT USER_ID, QUERY_TYPE, OBJECT_NAME, ACCESS_STATUS, COUNT(*) AS ATTEMPT_COUNT
FROM QUERY_LOGS
WHERE USER_ID = 1
AND QUERY_TYPE = 'DELETE'
GROUP BY USER_ID, QUERY_TYPE, OBJECT_NAME, ACCESS_STATUS;


