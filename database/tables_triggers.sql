
CREATE OR REPLACE TRIGGER TRG_LOGIN_FAILURE_USER
BEFORE INSERT ON LOGIN_FAILURES
FOR EACH ROW
DECLARE
    V_USER_ID NUMBER;
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        BEGIN
            SELECT USER_ID
            INTO V_USER_ID
            FROM DB_USERS
            WHERE USERNAME = :NEW.ATTEMPTED_USERNAME;

            :NEW.USER_ID := V_USER_ID;

        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                :NEW.USER_ID := NULL;
        END;
    END IF;
END;
/

COMMIT;
