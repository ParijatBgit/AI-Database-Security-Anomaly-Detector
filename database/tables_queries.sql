SELECT U.USERNAME, U.USER_ROLE,
       L.LOGIN_TIME, L.LOGOUT_TIME, L.IP_ADDRESS
FROM DB_USERS U
INNER JOIN LOGIN_HISTORY L
ON U.USER_ID = L.USER_ID;

SELECT U.USERNAME, Q.QUERY_TYPE,
       Q.OBJECT_NAME, Q.ACCESS_STATUS
FROM DB_USERS U
LEFT JOIN QUERY_LOGS Q
ON U.USER_ID = Q.USER_ID;

SELECT U.USERNAME, COUNT(Q.QUERY_ID) AS TOTAL_QUERIES
FROM DB_USERS U
JOIN QUERY_LOGS Q
ON U.USER_ID = Q.USER_ID
GROUP BY U.USERNAME
ORDER BY TOTAL_QUERIES DESC;

SELECT U.USERNAME, COUNT(Q.QUERY_ID) AS TOTAL_QUERIES
FROM DB_USERS U
JOIN QUERY_LOGS Q
ON U.USER_ID = Q.USER_ID
GROUP BY U.USERNAME
HAVING COUNT(Q.QUERY_ID) > 1;

SELECT U.USERNAME, COUNT(F.FAILURE_ID) AS FAILED_ATTEMPTS
FROM DB_USERS U
JOIN LOGIN_FAILURES F
ON U.USER_ID = F.USER_ID
GROUP BY U.USERNAME
HAVING COUNT(F.FAILURE_ID) > 1;

SELECT U.USERNAME,
       L.LOGIN_TIME,
       L.LOGOUT_TIME,
       ROUND((L.LOGOUT_TIME-L.LOGIN_TIME)*24,2)
       AS DURATION_HOURS
FROM DB_USERS U
JOIN LOGIN_HISTORY L
ON U.USER_ID = L.USER_ID;

SELECT U.USERNAME, Q.QUERY_TYPE,
       COUNT(*) AS TOTAL
FROM DB_USERS U
JOIN QUERY_LOGS Q
ON U.USER_ID = Q.USER_ID
GROUP BY U.USERNAME, Q.QUERY_TYPE
ORDER BY U.USERNAME;

SELECT U.USERNAME, Q.QUERY_TYPE,
       Q.OBJECT_NAME, Q.ACCESS_STATUS
FROM DB_USERS U
JOIN QUERY_LOGS Q
ON U.USER_ID = Q.USER_ID
WHERE NOT EXISTS (
    SELECT 1
    FROM USER_PERMISSIONS P
    WHERE P.USER_ID = Q.USER_ID
    AND P.OBJECT_NAME = Q.OBJECT_NAME
    AND (P.PERMISSION_TYPE = Q.QUERY_TYPE
         OR P.PERMISSION_TYPE = 'ALL')
);